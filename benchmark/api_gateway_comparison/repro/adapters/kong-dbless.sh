#!/usr/bin/env bash
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
suite_dir="$(cd "$script_dir/.." && pwd)"
product_dir="$suite_dir/products/kong"
kong_image="kong:3.9.1-ubuntu@sha256:76c14b93e989f7f4418039f7f9789ca32564016211c86ac1a18022f4788e7b9c"
: "${BENCH_PRODUCT_DIR:?BENCH_PRODUCT_DIR is required}"
state="$BENCH_PRODUCT_DIR/adapter.state"
mode_file="$BENCH_PRODUCT_DIR/adapter.mode"

die() {
  printf 'kong-dbless adapter: %s\n' "$*" >&2
  exit 1
}

load_state() {
  [[ -f "$state" ]] || die "state is missing; run prepare first"
  # This file contains names and paths generated by this adapter.
  source "$state"
}

wait_admin() {
  local code
  for _ in {1..400}; do
    code="$(curl -sS -o /dev/null -w '%{http_code}' --max-time 1 \
      "http://127.0.0.1:$BENCH_ADMIN_PORT/status" 2>/dev/null || true)"
    [[ "$code" == 200 ]] && return 0
    sleep 0.1
  done
  return 1
}

container_pids() {
  docker top "$1" -eo pid 2>/dev/null | awk 'NR > 1 && $1 ~ /^[0-9]+$/ {print $1}'
}

write_cgroup() {
  local pid
  pid="$(docker inspect -f '{{.State.Pid}}' "$container")"
  awk -F: '$1 == "0" {print $3}' "/proc/$pid/cgroup" >"$BENCH_PRODUCT_DIR/cgroup.path"
}

render_configs() {
  local version banned suffix
  for version in v1 v2; do
    for banned in 0 1; do
      suffix=unbanned
      ((banned)) && suffix=banned
      args=(
        --output "$configs/$version-$suffix.yml"
        --upstream-a "127.0.0.1:$BENCH_UPSTREAM_A_PORT"
        --upstream-b "127.0.0.1:$BENCH_UPSTREAM_B_PORT"
        --upstream-c "127.0.0.1:$BENCH_UPSTREAM_C_PORT"
        --upstream-d "127.0.0.1:$BENCH_UPSTREAM_D_PORT"
        --upstream-e "127.0.0.1:$BENCH_UPSTREAM_E_PORT"
        --jwt-secret "$BENCH_JWT_SECRET"
        --jwt-issuer "$BENCH_JWT_ISSUER"
        --banned-ip "$BENCH_BANNED_IP"
        --rate "$BENCH_RATE_REFILL"
        --version "$version"
        --upstream-count "${BENCH_UPSTREAM_COUNT:-5}"
      )
      [[ "${BENCH_CAPACITY_MODE:-0}" == 1 ]] && args+=(--main-ip-deny)
      ((banned)) && args+=(--banned)
      python3 "$product_dir/render.py" "${args[@]}"
    done
  done
}

apply_config() {
  local mode="$1" file="$configs/$1.yml"
  curl -fsS --max-time 10 -X POST -F "config=@$file" \
    "http://127.0.0.1:$BENCH_ADMIN_PORT/config" >"$BENCH_PRODUCT_DIR/snapshots/config-$mode.json"
  printf '%s\n' "$mode" >"$mode_file"
}

snapshot() {
  local label="$1" out="$BENCH_PRODUCT_DIR/snapshots/$1"
  mkdir -p "$out"
  curl -sS --max-time 3 "http://127.0.0.1:$BENCH_ADMIN_PORT/status" >"$out/status.json" || true
  curl -sS --max-time 3 "http://127.0.0.1:$BENCH_ADMIN_PORT/routes" >"$out/routes.json" || true
  curl -sS --max-time 3 "http://127.0.0.1:$BENCH_ADMIN_PORT/services" >"$out/services.json" || true
  curl -sS --max-time 3 "http://127.0.0.1:$BENCH_ADMIN_PORT/plugins" >"$out/plugins.json" || true
  curl -sS --max-time 3 "http://127.0.0.1:$BENCH_ADMIN_PORT/upstreams/bench-upstream/health" \
    >"$out/upstream-health.json" || true
  curl -sS --max-time 3 "http://127.0.0.1:$BENCH_ADMIN_PORT/metrics" >"$out/metrics.prom" || true
  docker inspect "$container" >"$out/container.json" 2>/dev/null || true
}

action="${1:-}"
case "$action" in
  preflight)
    for command in docker curl python3 sha256sum; do
      command -v "$command" >/dev/null || die "missing command $command"
    done
    docker info >/dev/null 2>&1 || die "Docker daemon is unavailable"
    docker image inspect "$kong_image" >/dev/null 2>&1 || docker pull "$kong_image" >/dev/null
    ;;
  prepare)
    case "${BENCH_UPSTREAM_COUNT:-5}" in 2|5) ;; *) die "BENCH_UPSTREAM_COUNT must be 2 or 5" ;; esac
    for name in BENCH_GATEWAY_PORT BENCH_ADMIN_PORT BENCH_UPSTREAM_A_PORT BENCH_UPSTREAM_B_PORT \
      BENCH_UPSTREAM_C_PORT BENCH_UPSTREAM_D_PORT BENCH_UPSTREAM_E_PORT BENCH_JWT_SECRET \
      BENCH_JWT_ISSUER BENCH_BANNED_IP BENCH_RATE_REFILL BENCH_MEMORY_BYTES; do
      [[ -n "${!name:-}" ]] || die "$name is required"
    done
    configs="$BENCH_PRODUCT_DIR/configs"
    runtime="$BENCH_PRODUCT_DIR/runtime"
    token="$(printf '%s' "$BENCH_PRODUCT_DIR" | sha256sum | cut -c1-12)"
    container="benchcmp-$token-kong-dbless"
    mkdir -p "$configs" "$runtime" "$BENCH_PRODUCT_DIR/logs" "$BENCH_PRODUCT_DIR/snapshots"
    render_configs
    cp -a "$product_dir/plugins" "$configs/plugins"
    cp "$product_dir/render.py" "$configs/render.py"
    docker image inspect "$kong_image" >"$configs/kong-image.json"
    sha256sum "$configs/"*.yml "$configs/render.py" \
      "$configs/plugins/bench-security/handler.lua" "$configs/plugins/bench-security/schema.lua" \
      >"$configs/artifacts.sha256"
    python3 - "$configs" <<'PY'
import pathlib, sys, yaml
for path in pathlib.Path(sys.argv[1]).glob("*.yml"):
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    assert data["_format_version"] == "3.0"
    assert data["services"] and data["upstreams"] and data["consumers"]
PY
    cat >"$BENCH_PRODUCT_DIR/capabilities.json" <<'JSON'
{
  "http_proxy": "PASS-INTERNAL",
  "websocket": "PASS-INTERNAL",
  "metrics": "PASS-PLUGIN",
  "routing": "PASS-INTERNAL",
  "jwt": "PASS-PLUGIN",
  "waf": "PASS-CUSTOM",
  "ip_ban": "PASS-PLUGIN",
  "rate_limit": "PASS-PLUGIN-FIXED-WINDOW",
  "weighted_least_connections": "PASS-INTERNAL",
  "active_health_check": "PASS-INTERNAL",
  "passive_health_isolation": "PASS-INTERNAL",
  "connection_pool": "PASS-INTERNAL-NGINX",
  "hot_reload": "PASS-INTERNAL",
  "high_precision_trace_toggle": "UNSUPPORTED",
  "external_control_plane": "NOT-APPLICABLE"
}
JSON
    cat >"$state" <<EOF
configs=$(printf '%q' "$configs")
runtime=$(printf '%q' "$runtime")
container=$(printf '%q' "$container")
EOF
    ;;
  start)
    load_state
    docker rm -f "$container" >/dev/null 2>&1 || true
    cp "$configs/v1-unbanned.yml" "$runtime/kong.yml"
    : >"$BENCH_PRODUCT_DIR/logs/kong-access.log"
    chmod 0666 "$BENCH_PRODUCT_DIR/logs/kong-access.log"
    docker run -d --name "$container" --network host \
      --cpus "${BENCH_KONG_CPUS:-1}" --cpuset-cpus "${BENCH_TARGET_CPU:-2}" \
      --memory "$BENCH_MEMORY_BYTES" --pids-limit 512 \
      -e KONG_DATABASE=off \
      -e KONG_DECLARATIVE_CONFIG=/runtime/kong.yml \
      -e "KONG_PROXY_LISTEN=127.0.0.1:$BENCH_GATEWAY_PORT reuseport" \
      -e "KONG_ADMIN_LISTEN=127.0.0.1:$BENCH_ADMIN_PORT reuseport" \
      -e KONG_STATUS_LISTEN=off \
      -e KONG_ADMIN_GUI_LISTEN=off \
      -e KONG_TRUSTED_IPS=127.0.0.1/32 \
      -e KONG_REAL_IP_HEADER=X-Forwarded-For \
      -e KONG_REAL_IP_RECURSIVE=on \
      -e "KONG_NGINX_WORKER_PROCESSES=${BENCH_GATEWAY_WORKERS:-1}" \
      -e KONG_PLUGINS=bundled,bench-security \
      -e KONG_LOG_LEVEL=notice \
      -v "$runtime:/runtime:ro" \
      -v "$product_dir/plugins/bench-security:/usr/local/share/lua/5.1/kong/plugins/bench-security:ro" \
      -v "$BENCH_PRODUCT_DIR:/evidence" \
      "$kong_image" >"$BENCH_PRODUCT_DIR/logs/container-id.txt"
    wait_admin || { docker logs "$container"; die "Kong did not become ready"; }
    printf 'v1-unbanned\n' >"$mode_file"
    write_cgroup
    snapshot started
    ;;
  ready)
    load_state
    wait_admin
    ;;
  reset-after-warmup)
    load_state
    printf '{"supported":false,"status":"NOOP","reason":"Kong DB-less has no circuit registry to reset"}\n' \
      >"$BENCH_PRODUCT_DIR/snapshots/reset-after-warmup.json"
    ;;
  pids)
    load_state
    container_pids "$container"
    ;;
  reload-valid)
    load_state
    current="$(cat "$mode_file")"
    apply_config "v2-${current#*-}"
    snapshot reload-valid
    ;;
  reload-invalid)
    load_state
    printf '_format_version: "3.0"\nservices: [\n' >"$runtime/invalid.yml"
    code="$(curl -sS --max-time 10 -o "$BENCH_PRODUCT_DIR/snapshots/reload-invalid.txt" \
      -w '%{http_code}' -X POST -F "config=@$runtime/invalid.yml" \
      "http://127.0.0.1:$BENCH_ADMIN_PORT/config" || true)"
    [[ "$code" != 2* ]] || die "invalid declarative config was accepted"
    wait_admin
    snapshot reload-invalid
    ;;
  restart-control)
    load_state
    printf '{"external_control_plane":false}\n' \
      >"$BENCH_PRODUCT_DIR/snapshots/control-plane-not-applicable.json"
    snapshot control-restarted
    ;;
  security-seed)
    load_state
    current="$(cat "$mode_file")"
    apply_config "${current%%-*}-banned"
    ;;
  security-unban)
    load_state
    current="$(cat "$mode_file")"
    apply_config "${current%%-*}-unbanned"
    ;;
  trace-on)
    load_state
    printf '{"supported":false,"reason":"no equivalent runtime high-precision trace toggle"}\n' \
      >"$BENCH_PRODUCT_DIR/snapshots/trace-on.json"
    snapshot trace-on
    ;;
  trace-off)
    load_state
    printf '{"supported":false}\n' >"$BENCH_PRODUCT_DIR/snapshots/trace-off.json"
    snapshot trace-off
    ;;
  observe-probe)
    load_state
    code="$(curl -sS --max-time 3 -o "$BENCH_PRODUCT_DIR/snapshots/observe-body.json" \
      -D "$BENCH_PRODUCT_DIR/snapshots/observe-headers.txt" -w '%{http_code}' \
      -H "Authorization: Bearer $BENCH_VALID_TOKEN" \
      -H 'X-Forwarded-For: 198.18.80.80' -H 'X-Request-ID: bench-observe-fixed' \
      "$BENCH_GATEWAY_URL/probe/observe")"
    [[ "$code" == 200 ]] || die "observation probe returned HTTP $code"
    ;;
  observe-verify)
    load_state
    for _ in {1..30}; do
      grep -F 'bench-observe-fixed' "$BENCH_PRODUCT_DIR/logs/kong-access.log" \
        >"$BENCH_PRODUCT_DIR/snapshots/observe-access.log" 2>/dev/null && break
      sleep 0.1
    done
    [[ -s "$BENCH_PRODUCT_DIR/snapshots/observe-access.log" ]] \
      || die "request id missing from Kong access log"
    snapshot observe-verified
    ;;
  log-rotate)
    load_state
    log="$BENCH_PRODUCT_DIR/logs/kong-access.log"
    if [[ -f "$log" ]]; then
      cp "$log" "$log.1"
      : >"$log"
    fi
    snapshot log-rotated
    ;;
  snapshot*)
    load_state
    snapshot "$action"
    ;;
  stop)
    if [[ -f "$state" ]]; then
      load_state
      docker logs "$container" >"$BENCH_PRODUCT_DIR/logs/kong-process.log" 2>&1 || true
      docker rm -f "$container" >/dev/null 2>&1 || true
    fi
    ;;
  *)
    die "unknown action: $action"
    ;;
esac
