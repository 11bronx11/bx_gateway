#!/usr/bin/env bash
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
suite_dir="$(cd "$script_dir/.." && pwd)"
product_dir="$suite_dir/products/kong"
kong_image="kong:3.9.1-ubuntu@sha256:76c14b93e989f7f4418039f7f9789ca32564016211c86ac1a18022f4788e7b9c"
postgres_image="postgres:17-alpine@sha256:18cfe3ef5e6815560c98237d6216d1e5119702fb0f3894c8785dd58b8bbe5d73"
: "${BENCH_PRODUCT_DIR:?BENCH_PRODUCT_DIR is required}"
state="$BENCH_PRODUCT_DIR/adapter.state"
ip_plugin_file="$BENCH_PRODUCT_DIR/ip-plugin.id"

die() {
  printf 'kong-postgres adapter: %s\n' "$*" >&2
  exit 1
}

load_state() {
  [[ -f "$state" ]] || die "state is missing; run prepare first"
  # This file contains names, ports and paths generated by this adapter.
  source "$state"
}

wait_admin() {
  local code
  for _ in {1..500}; do
    code="$(curl -sS -o /dev/null -w '%{http_code}' --max-time 1 \
      "http://127.0.0.1:$BENCH_ADMIN_PORT/status" 2>/dev/null || true)"
    [[ "$code" == 200 ]] && return 0
    sleep 0.1
  done
  return 1
}

wait_postgres() {
  for _ in {1..300}; do
    docker exec "$postgres_container" pg_isready -U kong -d kong >/dev/null 2>&1 && return 0
    sleep 0.1
  done
  return 1
}

container_pids() {
  docker top "$1" -eo pid 2>/dev/null | awk 'NR > 1 && $1 ~ /^[0-9]+$/ {print $1}'
}

append_cgroup() {
  local pid
  pid="$(docker inspect -f '{{.State.Pid}}' "$1")"
  awk -F: '$1 == "0" {print $3}' "/proc/$pid/cgroup"
}

kong_env() {
  printf '%s\n' \
    -e KONG_DATABASE=postgres \
    -e KONG_PG_HOST=127.0.0.1 \
    -e "KONG_PG_PORT=$BENCH_HUB_PORT" \
    -e KONG_PG_USER=kong \
    -e KONG_PG_PASSWORD=kong-bench \
    -e KONG_PG_DATABASE=kong \
    -e KONG_PLUGINS=bundled,bench-security
}

snapshot() {
  local label="$1" out="$BENCH_PRODUCT_DIR/snapshots/$1"
  mkdir -p "$out"
  curl -sS --max-time 3 "http://127.0.0.1:$BENCH_ADMIN_PORT/status" >"$out/status.json" || true
  curl -sS --max-time 3 "http://127.0.0.1:$BENCH_ADMIN_PORT/routes" >"$out/routes.json" || true
  curl -sS --max-time 3 "http://127.0.0.1:$BENCH_ADMIN_PORT/services" >"$out/services.json" || true
  curl -sS --max-time 3 "http://127.0.0.1:$BENCH_ADMIN_PORT/plugins" >"$out/plugins.json" || true
  curl -sS --max-time 3 "http://127.0.0.1:$BENCH_ADMIN_PORT/upstreams/bench-upstream/health" \
    >"$out/upstream-health.json" || true
  curl -sS --max-time 3 "http://127.0.0.1:$BENCH_ADMIN_PORT/metrics" >"$out/metrics.prom" || true
  docker inspect "$kong_container" >"$out/kong-container.json" 2>/dev/null || true
  docker inspect "$postgres_container" >"$out/postgres-container.json" 2>/dev/null || true
  du -sb "$runtime/pgdata" >"$out/postgres-bytes.txt" 2>/dev/null || true
}

service_plugin_id() {
  local service="$1" name="$2"
  curl -fsS --max-time 5 "http://127.0.0.1:$BENCH_ADMIN_PORT/services/$service/plugins" \
    | jq -er --arg name "$name" '.data[] | select(.name == $name) | .id' | head -1
}

action="${1:-}"
case "$action" in
  preflight)
    for command in docker curl python3 jq sha256sum; do
      command -v "$command" >/dev/null || die "missing command $command"
    done
    docker info >/dev/null 2>&1 || die "Docker daemon is unavailable"
    docker image inspect "$kong_image" >/dev/null 2>&1 || docker pull "$kong_image" >/dev/null
    docker image inspect "$postgres_image" >/dev/null 2>&1 || docker pull "$postgres_image" >/dev/null
    ;;
  prepare)
    case "${BENCH_UPSTREAM_COUNT:-5}" in 2|5) ;; *) die "BENCH_UPSTREAM_COUNT must be 2 or 5" ;; esac
    for name in BENCH_GATEWAY_PORT BENCH_ADMIN_PORT BENCH_HUB_PORT BENCH_UPSTREAM_A_PORT \
      BENCH_UPSTREAM_B_PORT BENCH_UPSTREAM_C_PORT BENCH_UPSTREAM_D_PORT BENCH_UPSTREAM_E_PORT \
      BENCH_JWT_SECRET BENCH_JWT_ISSUER BENCH_BANNED_IP BENCH_RATE_REFILL \
      BENCH_KONG_MEMORY_BYTES BENCH_PG_MEMORY_BYTES; do
      [[ -n "${!name:-}" ]] || die "$name is required"
    done
    configs="$BENCH_PRODUCT_DIR/configs"
    runtime="$BENCH_PRODUCT_DIR/runtime"
    token="$(printf '%s' "$BENCH_PRODUCT_DIR" | sha256sum | cut -c1-12)"
    kong_container="benchcmp-$token-kong-postgres"
    postgres_container="benchcmp-$token-postgres"
    mkdir -p "$configs" "$runtime/pgdata" "$BENCH_PRODUCT_DIR/logs" "$BENCH_PRODUCT_DIR/snapshots"
    render_args=(
      --output "$configs/initial.yml" \
      --upstream-a "127.0.0.1:$BENCH_UPSTREAM_A_PORT" \
      --upstream-b "127.0.0.1:$BENCH_UPSTREAM_B_PORT" \
      --upstream-c "127.0.0.1:$BENCH_UPSTREAM_C_PORT" \
      --upstream-d "127.0.0.1:$BENCH_UPSTREAM_D_PORT" \
      --upstream-e "127.0.0.1:$BENCH_UPSTREAM_E_PORT" \
      --jwt-secret "$BENCH_JWT_SECRET" --jwt-issuer "$BENCH_JWT_ISSUER" \
      --banned-ip "$BENCH_BANNED_IP" --rate "$BENCH_RATE_REFILL" \
      --version v1 --upstream-count "${BENCH_UPSTREAM_COUNT:-5}"
    )
    [[ "${BENCH_CAPACITY_MODE:-0}" == 1 ]] && render_args+=(--main-ip-deny)
    python3 "$product_dir/render.py" "${render_args[@]}"
    cp -a "$product_dir/plugins" "$configs/plugins"
    cp "$product_dir/render.py" "$configs/render.py"
    docker image inspect "$kong_image" >"$configs/kong-image.json"
    docker image inspect "$postgres_image" >"$configs/postgres-image.json"
    sha256sum "$configs/initial.yml" "$configs/render.py" \
      "$configs/plugins/bench-security/handler.lua" "$configs/plugins/bench-security/schema.lua" \
      >"$configs/artifacts.sha256"
    cat >"$BENCH_PRODUCT_DIR/capabilities.json" <<'JSON'
{
  "http_proxy": "PASS-INTERNAL",
  "websocket": "PASS-INTERNAL",
  "metrics": "PASS-PLUGIN",
  "routing": "PASS-INTERNAL",
  "jwt": "PASS-PLUGIN",
  "waf": "PASS-CUSTOM",
  "ip_ban": "PASS-PLUGIN",
  "rate_limit": "PASS-PLUGIN-FIXED-WINDOW",
  "weighted_least_connections": "PASS-INTERNAL",
  "active_health_check": "PASS-INTERNAL",
  "passive_health_isolation": "PASS-INTERNAL",
  "connection_pool": "PASS-INTERNAL-NGINX",
  "hot_reload": "PASS-ADMIN-API",
  "high_precision_trace_toggle": "UNSUPPORTED",
  "external_control_plane": "POSTGRESQL"
}
JSON
    cat >"$state" <<EOF
configs=$(printf '%q' "$configs")
runtime=$(printf '%q' "$runtime")
kong_container=$(printf '%q' "$kong_container")
postgres_container=$(printf '%q' "$postgres_container")
EOF
    ;;
  start)
    load_state
    docker rm -f "$kong_container" "$postgres_container" >/dev/null 2>&1 || true
    docker run -d --name "$postgres_container" --network host \
      --cpus "${BENCH_PG_CPUS:-0.25}" --cpuset-cpus "${BENCH_TARGET_CPU:-2}" \
      --memory "$BENCH_PG_MEMORY_BYTES" --pids-limit 128 \
      -e POSTGRES_USER=kong -e POSTGRES_PASSWORD=kong-bench -e POSTGRES_DB=kong \
      -e PGPORT="$BENCH_HUB_PORT" \
      -v "$runtime/pgdata:/var/lib/postgresql/data" \
      "$postgres_image" postgres -c shared_buffers=32MB -c max_connections=30 -c work_mem=1MB \
      >"$BENCH_PRODUCT_DIR/logs/postgres-container-id.txt"
    wait_postgres || { docker logs "$postgres_container"; die "PostgreSQL did not become ready"; }
    mapfile -t db_env < <(kong_env)
    docker run --rm --network host "${db_env[@]}" \
      -v "$product_dir/plugins/bench-security:/usr/local/share/lua/5.1/kong/plugins/bench-security:ro" \
      "$kong_image" kong migrations bootstrap
    docker run --rm --network host "${db_env[@]}" \
      -v "$configs:/runtime:ro" \
      -v "$product_dir/plugins/bench-security:/usr/local/share/lua/5.1/kong/plugins/bench-security:ro" \
      "$kong_image" kong config db_import /runtime/initial.yml
    : >"$BENCH_PRODUCT_DIR/logs/kong-access.log"
    chmod 0666 "$BENCH_PRODUCT_DIR/logs/kong-access.log"
    docker run -d --name "$kong_container" --network host \
      --cpus "${BENCH_KONG_CPUS:-0.75}" --cpuset-cpus "${BENCH_TARGET_CPU:-2}" \
      --memory "$BENCH_KONG_MEMORY_BYTES" --pids-limit 512 \
      "${db_env[@]}" \
      -e "KONG_PROXY_LISTEN=127.0.0.1:$BENCH_GATEWAY_PORT reuseport" \
      -e "KONG_ADMIN_LISTEN=127.0.0.1:$BENCH_ADMIN_PORT reuseport" \
      -e KONG_STATUS_LISTEN=off -e "KONG_NGINX_WORKER_PROCESSES=${BENCH_GATEWAY_WORKERS:-1}" \
      -e KONG_ADMIN_GUI_LISTEN=off \
      -e KONG_TRUSTED_IPS=127.0.0.1/32 -e KONG_REAL_IP_HEADER=X-Forwarded-For \
      -e KONG_REAL_IP_RECURSIVE=on -e KONG_LOG_LEVEL=notice \
      -v "$product_dir/plugins/bench-security:/usr/local/share/lua/5.1/kong/plugins/bench-security:ro" \
      -v "$BENCH_PRODUCT_DIR:/evidence" \
      "$kong_image" >"$BENCH_PRODUCT_DIR/logs/kong-container-id.txt"
    wait_admin || { docker logs "$kong_container"; die "Kong did not become ready"; }
    {
      append_cgroup "$kong_container"
      append_cgroup "$postgres_container"
    } >"$BENCH_PRODUCT_DIR/cgroup.path"
    snapshot started
    ;;
  ready)
    load_state
    wait_admin
    wait_postgres
    ;;
  pids)
    load_state
    container_pids "$kong_container"
    container_pids "$postgres_container"
    ;;
  reload-valid)
    load_state
    jq -n '{config:{add:{headers:["X-Bench-Version:v2"]},remove:{headers:["X-Internal-Debug"]}}}' \
      >"$runtime/reload-valid.json"
    responses=()
    for service in bench-service bench-ban-service bench-ws-service; do
      id="$(service_plugin_id "$service" request-transformer)"
      response="$runtime/reload-valid-$service.json"
      curl -fsS --max-time 5 -X PATCH -H 'Content-Type: application/json' \
        --data-binary "@$runtime/reload-valid.json" \
        "http://127.0.0.1:$BENCH_ADMIN_PORT/plugins/$id" >"$response"
      jq -e --arg service "$service" \
        '.name == "request-transformer"
         and .config.add.headers == ["X-Bench-Version:v2"]
         and .config.remove.headers == ["X-Internal-Debug"]
         and .service.id != null' "$response" >/dev/null
      responses+=("$response")
    done
    jq -s . "${responses[@]}" >"$BENCH_PRODUCT_DIR/snapshots/reload-valid.json"
    snapshot reload-valid
    ;;
  reload-invalid)
    load_state
    id="$(service_plugin_id bench-service rate-limiting)"
    code="$(curl -sS --max-time 5 -o "$BENCH_PRODUCT_DIR/snapshots/reload-invalid.txt" \
      -w '%{http_code}' -X PATCH -H 'Content-Type: application/json' \
      -d '{"config":{"second":-1}}' \
      "http://127.0.0.1:$BENCH_ADMIN_PORT/plugins/$id" || true)"
    [[ "$code" != 2* ]] || die "invalid plugin configuration was accepted"
    wait_admin
    snapshot reload-invalid
    ;;
  restart-control)
    load_state
    docker restart "$postgres_container" >/dev/null
    wait_postgres || die "PostgreSQL did not recover"
    snapshot control-restarted
    ;;
  security-seed)
    load_state
    if [[ ! -s "$ip_plugin_file" ]]; then
      curl -fsS --max-time 5 -X POST \
        -d name=ip-restriction --data-urlencode "config.deny=$BENCH_BANNED_IP" \
        "http://127.0.0.1:$BENCH_ADMIN_PORT/services/bench-ban-service/plugins" \
        >"$BENCH_PRODUCT_DIR/snapshots/security-seed.json"
      jq -er '.id' "$BENCH_PRODUCT_DIR/snapshots/security-seed.json" >"$ip_plugin_file"
    fi
    ;;
  security-unban)
    load_state
    if [[ -s "$ip_plugin_file" ]]; then
      id="$(cat "$ip_plugin_file")"
      curl -fsS --max-time 5 -X DELETE \
        "http://127.0.0.1:$BENCH_ADMIN_PORT/plugins/$id" \
        >"$BENCH_PRODUCT_DIR/snapshots/security-unban.json"
      : >"$ip_plugin_file"
    fi
    ;;
  trace-on)
    load_state
    printf '{"supported":false,"reason":"no equivalent runtime high-precision trace toggle"}\n' \
      >"$BENCH_PRODUCT_DIR/snapshots/trace-on.json"
    snapshot trace-on
    ;;
  trace-off)
    load_state
    printf '{"supported":false}\n' >"$BENCH_PRODUCT_DIR/snapshots/trace-off.json"
    snapshot trace-off
    ;;
  observe-probe)
    load_state
    code="$(curl -sS --max-time 3 -o "$BENCH_PRODUCT_DIR/snapshots/observe-body.json" \
      -D "$BENCH_PRODUCT_DIR/snapshots/observe-headers.txt" -w '%{http_code}' \
      -H "Authorization: Bearer $BENCH_VALID_TOKEN" \
      -H 'X-Forwarded-For: 198.18.80.80' -H 'X-Request-ID: bench-observe-fixed' \
      "$BENCH_GATEWAY_URL/probe/observe")"
    [[ "$code" == 200 ]] || die "observation probe returned HTTP $code"
    ;;
  observe-verify)
    load_state
    for _ in {1..30}; do
      grep -F 'bench-observe-fixed' "$BENCH_PRODUCT_DIR/logs/kong-access.log" \
        >"$BENCH_PRODUCT_DIR/snapshots/observe-access.log" 2>/dev/null && break
      sleep 0.1
    done
    [[ -s "$BENCH_PRODUCT_DIR/snapshots/observe-access.log" ]] \
      || die "request id missing from Kong access log"
    snapshot observe-verified
    ;;
  log-rotate)
    load_state
    log="$BENCH_PRODUCT_DIR/logs/kong-access.log"
    if [[ -f "$log" ]]; then
      cp "$log" "$log.1"
      : >"$log"
    fi
    snapshot log-rotated
    ;;
  snapshot*)
    load_state
    snapshot "$action"
    ;;
  stop)
    if [[ -f "$state" ]]; then
      load_state
      docker logs "$kong_container" >"$BENCH_PRODUCT_DIR/logs/kong-process.log" 2>&1 || true
      docker logs "$postgres_container" >"$BENCH_PRODUCT_DIR/logs/postgres-process.log" 2>&1 || true
      docker exec -u 0 "$postgres_container" chmod -R a+rX /var/lib/postgresql/data \
        >/dev/null 2>&1 || true
      docker rm -f "$kong_container" "$postgres_container" >/dev/null 2>&1 || true
    fi
    ;;
  *)
    die "unknown action: $action"
    ;;
esac
